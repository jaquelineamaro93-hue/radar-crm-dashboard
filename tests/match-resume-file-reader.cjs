'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const read=path=>fs.readFileSync(path,'utf8');
const src=read('assets/match-resume-file-reader.js'),hub=read('assets/profile-hub-unified.js'),css=read('assets/profile-hub-unified.css'),html=read('index.html');
new vm.Script(src,{filename:'match-resume-file-reader.js'});
assert(src.includes("document.createElement('input')"));
assert(src.includes("input.type='file'"));
assert(src.includes("input.accept='.pdf,.docx,.txt,.md"));
assert(src.includes("await file.arrayBuffer()"),'file is read locally');
assert(src.includes("cv.dispatchEvent(new Event('input',{bubbles:true}))"),'draft reflects imported text');
assert(src.includes("window.confirm('Substituir"),'existing CV is never overwritten silently');
assert(src.includes("apply.disabled=true"),'review is required before inserting');
assert(!/\b(?:XMLHttpRequest|sendBeacon)\b/.test(src),'no upload channel');
assert(!src.includes('fetch('),'the file contents are not posted to any endpoint');
assert(src.includes('cdnjs.cloudflare.com/ajax/libs/pdf.js/4.10.38/pdf.min.mjs'));
assert(src.includes('cdnjs.cloudflare.com/ajax/libs/mammoth/1.10.0/mammoth.browser.min.js'));
assert(hub.includes("const resume=panel('cx-profile-tab-match'"));
assert(html.includes('match-resume-file-reader.js?v=20261030-docreader1'));
assert(html.includes('profile-hub-unified.js?v=20261030-matchhub2'));
assert(html.includes('.crm-match-chip.is-selected{background:#342545;color:#f2ddfc;border-color:#b48bd2}'));
assert(!html.includes('.crm-match-chip.is-selected{background:#f97316'),'old unreadable orange chip source must be removed');
assert(css.includes('#crmMatchResumeOverlay .crm-match-chip.is-selected'));
assert(css.includes('font-size:12px!important'));
const window={};
const document={readyState:'loading',addEventListener:()=>{}};
class MutationObserver{observe(){}}
vm.runInNewContext(src,{window,document,MutationObserver,Promise,Array,String,Error,Number,Uint8Array,Uint16Array,Math,Intl});
assert(window.CXResumeDocumentReader,'reader must be available on the page');
(async()=>{
 const get=window.CXResumeDocumentReader.extractText;
 const sample=await get({name:'meu-cv.txt',size:205,text:async()=>('Experiência profissional\nCRM e Customer Success. '.repeat(10))});
 assert(sample.includes('Experiência profissional'));
 await assert.rejects(()=>get({name:'foto.png',size:202}),/Formatos aceitos/);
 await assert.rejects(()=>get({name:'muito-grande.pdf',size:6*1024*1024}),/5 MB/);
 await assert.rejects(()=>get({name:'vazio.txt',size:3,text:async()=>''}),/texto suficiente/);
 console.log('PASS private Match resume tab, accessible lilac styling, local file parsing and explicit review');
})().catch(err=>{console.error(err);process.exitCode=1});
