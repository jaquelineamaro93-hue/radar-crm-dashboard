const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('cases/index.html', 'utf8');
const favicon = fs.readFileSync('favicon.svg', 'utf8');
const png = fs.readFileSync('apple-touch-icon.png');

assert.match(html, /<nav class="wrap nav" aria-label="Navegação principal">/);
assert.match(html, /<meta name="theme-color" content="#10192a">/);
assert.match(html, /rel="icon"[^>]+favicon\.svg\?v=20261028/);
assert.match(html, /rel="apple-touch-icon"[^>]+apple-touch-icon\.png\?v=20261028/);
assert.match(html, /--accent:#ce9cea/);
assert.match(html, /--bg:#0e1626/);
assert.match(html, /@media\(max-width:620px\)/);
assert.match(html, /id="case-videos"[^>]*hidden/);
assert.doesNotMatch(html, /#f97316|#F97316|#272019|#fff6f0/);
assert.match(favicon, /#CE9CEA/);
assert.equal(png.subarray(0,8).toString('hex'), '89504e470d0a1a0a', 'iPhone touch icon must be a valid PNG');
assert.match(html, /assets\/site-i18n\.js/);
assert.match(html, /assets\/case-videos\.js/);
console.log('PASS Cases brand, mobile layout, localization, safe video gallery and mobile icons');
