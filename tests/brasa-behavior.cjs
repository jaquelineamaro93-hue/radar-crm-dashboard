'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
(async()=>{
 const {Window}=await import(process.env.HAPPY_DOM_MODULE||'happy-dom');
 const window=new Window({url:'https://conexaocrm.com/membros/'}),document=window.document;
 document.body.innerHTML='<div id="view-logada"></div>';
 let user={id:'first'},routes=[];
 const rows=Array.from({length:6},(_,i)=>({nivel:'Analista Pleno',modelo:'Remoto',regiao:'Sudeste',salario:5000+i*1000}));
 const context=vm.createContext({window,document,location:window.location,MutationObserver:window.MutationObserver,Event:window.Event,setInterval:()=>0,setTimeout,crmSignedIn:()=>!!user,CARGOS_ROWS:rows,crmNavigate:r=>routes.push(r),get CURRENT_USER(){return user}});
 vm.runInContext(fs.readFileSync('assets/crm-copilot.js','utf8'),context);
 document.dispatchEvent(new window.Event('DOMContentLoaded'));
 window.CXCopilot.open();
 const root=document.getElementById('cxCopilot'),history=root.querySelector('[role=log]'),panel=document.getElementById('cxCopilotPanel');
 assert.equal(root.querySelector('.cx-copilot-privacy'),null);
 const expand=root.querySelector('[data-cx-expand]');
 expand.click();assert.equal(root.classList.contains('cx-expanded'),true);assert.equal(expand.textContent,'Reduzir');
 expand.click();assert.equal(root.classList.contains('cx-expanded'),false);
 const ask=text=>{const e=root.querySelector('textarea');e.value=text;root.querySelector('form').dispatchEvent(new window.Event('submit',{cancelable:true}));};
 const salary=[...root.querySelectorAll('[data-cx-quick] button')].find(b=>b.textContent==='Médias salariais');
 salary.click();assert.equal(routes.length,0,'suggestions must never navigate');assert.match(history.textContent,/7.500/);assert.match(history.textContent,/6 salários/);
 ask('E pleno remoto?');assert.match(history.lastElementChild.textContent,/7.500/);
 const before=history.innerHTML;
 document.getElementById('view-logada').hidden=true;document.dispatchEvent(new window.Event('crm:route-changed'));
 assert.equal(root.hidden,true);assert.equal(history.innerHTML,before,'public-route visibility preserves own memory');
 document.getElementById('view-logada').hidden=false;document.dispatchEvent(new window.Event('crm:route-changed'));
 assert.equal(document.getElementById('cxCopilot'),root);assert.equal(panel.hidden,false);
 history.lastElementChild.querySelector('button').click();assert.deepEqual(routes,['cargos']);assert.equal(panel.hidden,false);
 ask('quanto ganha em SP?');assert.match(history.lastElementChild.textContent,/Sudeste/);assert.match(history.lastElementChild.textContent,/7.500/);
 ask('e mensal?');assert.match(history.lastElementChild.textContent,/não informa se os valores são mensais ou anuais/);
 ask('mas é de São Paulo?');assert.match(history.lastElementChild.textContent,/não consigo afirmar que essa média seja exclusiva de SP/i);
 ask('salário de diretor remoto');assert.match(history.lastElementChild.textContent,/Não encontrei salários/);
 ask('<img src=x onerror=alert(1)>');assert.equal(history.querySelector('img'),null);
 ask(('Requisitos: experiência com CRM e SQL. ').repeat(8));assert.match(history.lastElementChild.textContent,/O Brasa não acessa seu perfil ou currículo/);
 const consentCard=history.querySelector('.cx-copilot-consent');
 assert.ok(consentCard,'first external request must ask for consent');
 consentCard.querySelector('button').click();
 assert.match(document.cookie,/crm_brasa_aceite_v2_/,'consent preference saved per account');
 assert.equal(root.querySelector('[data-cx-privacy-settings]').hidden,false);
 ask(('Requisitos: experiência com CRM e SQL. ').repeat(8));
 assert.equal(history.querySelector('.cx-copilot-consent'),null,'subsequent requests reuse consent');
 root.querySelector('[data-cx-privacy-settings]').click();
 assert.doesNotMatch(document.cookie,/crm_brasa_aceite_v2_/,'consent can be revoked');
 ask(('Requisitos: experiência com CRM e SQL. ').repeat(8));
 assert.ok(history.querySelector('.cx-copilot-consent'),'revoked consent asks again');
 user={id:'second'};document.dispatchEvent(new window.Event('crm:auth-state'));
 assert.equal(history.children.length,1,'new account must clear conversation');
 user=null;document.dispatchEvent(new window.Event('crm:auth-state'));assert.equal(document.getElementById('cxCopilot'),null);
 await window.happyDOM.close();
 console.log('PASS: suggestions, real aggregate answers, route persistence, account isolation, XSS and paid-call block');
})().catch(e=>{console.error(e);process.exitCode=1});
